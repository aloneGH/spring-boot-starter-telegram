    private static final Map<Character, Character> MAP = new HashMap<>(1024);

    static {
        int len = Math.min(TRAD.length(), SIMP.length());
        for (int i = 0; i < len; i++) {
            char t = TRAD.charAt(i);
            char s = SIMP.charAt(i);
            if (t != s) {
                MAP.putIfAbsent(t, s);
            }
        }
    }

    private ChineseNormalizer() {
    }

    /**
     * 繁体转简体 + 全角 ASCII 转半角。
     */
    public static String toSimplifiedAndHalfWidth(String input) {
        if (input == null || input.isEmpty()) {
            return "";
        }
        StringBuilder sb = new StringBuilder(input.length());
        for (int i = 0; i < input.length(); i++) {
            char c = input.charAt(i);
            if (c == '\u3000') {
                sb.append(' ');
            } else if (c >= '\uFF01' && c <= '\uFF5E') {
                sb.append((char) (c - 0xFEE0));
            } else {
                sb.append(MAP.getOrDefault(c, c));
            }
        }
        return sb.toString();
    }
